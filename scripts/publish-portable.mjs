import { mkdir, readdir, rename, rm } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const projectRoot = resolve(process.cwd());
const outputDirectoryName = "release";
const allowedSourceDirectories = new Set([".portable-staging", "release-013"]);
const sourceArgument = process.argv.find((argument) => argument.startsWith("--source="));
const sourceDirectoryName = sourceArgument ? sourceArgument.slice("--source=".length) : ".portable-staging";

if (!allowedSourceDirectories.has(sourceDirectoryName)) {
  throw new Error(`Unsupported publish source: ${sourceDirectoryName}`);
}

function workspaceChild(name) {
  const target = resolve(projectRoot, name);
  const pathFromRoot = relative(projectRoot, target);
  if (!pathFromRoot || pathFromRoot.startsWith("..") || pathFromRoot.includes("\\..\\")) {
    throw new Error(`Refusing to operate outside the project workspace: ${target}`);
  }
  return target;
}

const sourceDirectory = workspaceChild(sourceDirectoryName);
const outputDirectory = workspaceChild(outputDirectoryName);
const artifacts = (await readdir(sourceDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && /^Codex-Usage-Companion-.*-portable\.exe$/i.test(entry.name));

if (artifacts.length !== 1) {
  throw new Error(`Expected exactly one Portable EXE in ${sourceDirectory}, found ${artifacts.length}.`);
}

const artifactName = artifacts[0].name;
const sourceArtifact = join(sourceDirectory, artifactName);

// `release` is intentionally the one and only user-facing artifact directory.
await rm(outputDirectory, {
  recursive: true,
  force: true,
  maxRetries: 12,
  retryDelay: 250
});
await mkdir(outputDirectory, { recursive: true });
await rename(sourceArtifact, join(outputDirectory, artifactName));

// Everything below is generated by a successful portable build and can be recreated.
for (const directoryName of [".portable-staging", "dist", "dist-blue", "release-013", "out", "build"]) {
  const directory = workspaceChild(directoryName);
  if (directory !== outputDirectory) await rm(directory, { recursive: true, force: true });
}

console.log(`Published ${join(outputDirectoryName, artifactName)} and removed temporary build artifacts.`);
